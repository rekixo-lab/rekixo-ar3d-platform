 const unified=read("app/api/client/metro-status/route.ts");
 assert.match(unified,/env.DB.batch\(statements\)/);
 assert.doesNotMatch(unified,/AGREEMENT_REQUIRES_SALE|SALE_DETAILS_REQUIRED/);
